// RecordOrderSettlement persists one fill/settlement atomically in a single
// transaction: per-asset balance (realized P&L delta-accumulated inside the
// tx), the engine-applied account blocks, the optional trade, the fill event(s),
// the optional lock rewrite and the order
// status advance commit or roll back together. A zero st.Order is an
// in-memory-only hold with no order row: the order/event/lock writes are skipped
// and only the balance and block effects run. When AllowedFrom is
// non-empty the status UPDATE is guarded and a disallowed current status yields
// domain.ErrConflict with nothing written; otherwise a missing order yields
// domain.ErrNotFound. The block-audit row is NOT part of this tx; callers write
// it separately after a successful commit.
func (r *realmStore) RecordOrderSettlement(
	ctx context.Context, st domain.OrderSettlement,
) error {
	return r.recordOrderSettlement(ctx, st, nil)
}

func (r *realmStore) RecordOrderSettlementWithAttestation(
	ctx context.Context, st domain.OrderSettlement, attest fwstore.EventAttestor,
) error {
	return r.recordOrderSettlement(ctx, st, attest)
}

func (r *realmStore) recordOrderSettlement(
	ctx context.Context, st domain.OrderSettlement, attest fwstore.EventAttestor,
) error {
	db, err := r.db()
	if err != nil {
		return err
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("store: begin record_order_settlement: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	if err := r.recordOrderSettlementTx(ctx, tx, st, attest); err != nil {
		return err
	}
	if err := tx.Commit(); err != nil {
		return fmt.Errorf("store: commit record_order_settlement: %w", err)
	}
	return nil
}

func (r *realmStore) recordOrderSettlementTx(
	ctx context.Context, tx *sql.Tx, st domain.OrderSettlement, attest fwstore.EventAttestor,
) error {
	// Resolve the settling account once; balance and blocks reuse it. The
	// account is the fill's account, always present on a settlement.
	accountID, err := resolveAccountID(ctx, tx, st.Account)
	if err != nil {
		return err
	}

	if st.ReservationApprovalID != "" {
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE reservation_intent SET state = ? WHERE approval_id = ?`,
			string(st.ReservationIntentState), st.ReservationApprovalID,
		); err != nil {
			return fmt.Errorf("store: settlement reservation intent state: %w", err)
		}
	}

	// Insert the initial held-intent row for a hold-accept settlement in the same
	// transaction as the order, so the order row and its durable reservation record
	// are atomic. The engine builds the intent but never writes it (a nested write
	// would self-deadlock on the single connection held by this transaction).
	if st.ReservationIntentUpsert != nil {
		if err := upsertReservationIntentTx(ctx, tx, *st.ReservationIntentUpsert); err != nil {
			return err
		}
	}

	// Per-asset balance: read-modify-write inside the tx so the realized-P&L
	// accumulate is consistent under the tx snapshot (SQLite serializes writers).
	for _, bal := range st.Balances {
		if err := settleBalanceTx(ctx, tx, accountID, bal); err != nil {
			return err
		}
	}

	// Mirror engine-applied account blocks (the block UPDATE only; the audit row
	// stays a post-commit write owned by the caller). A block names its own
	// account, which may differ from the fill account in principle, so resolve it.
	for _, blk := range st.Blocks {
		blkAccountID, err := resolveAccountID(ctx, tx, blk.Account)
		if err != nil {
			return err
		}
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE account SET blocked = ?, block_reason = ? WHERE id = ?`,
			true, blk.Reason, blkAccountID,
		); err != nil {
			return fmt.Errorf("store: settlement mirror block %q: %w", blk.Account, err)
		}
	}

	// Trade row.
	if st.Trade != nil {
		if _, _, err := r.insertTrade(ctx, tx, *st.Trade); err != nil {
			return err
		}
	}

	// The remaining writes touch the order row; an in-memory-only hold (zero
	// Order) carries no order row, so skip them and only the balance/block
	// effects above run.
	if st.Order.IsZero() {
		return nil
	}

	// Resolve the order surrogate id once; events, the optional lock rewrite and
	// the status advance all reuse it.
	orderID, err := lookupOrderID(ctx, tx, st.Order)
	if err != nil {
		return err
	}
	if attest != nil && len(st.Events) == 0 {
		return fmt.Errorf(
			"store: settlement has no event to attest: %w", domain.ErrInvalid,
		)
	}

	// Fill event(s).
	for _, ev := range st.Events {
		recorded, err := appendOrderEventReturningTx(ctx, tx, orderID, ev)
		if err != nil {
			return err
		}
		if err := attestOrderEventTx(ctx, tx, recorded, attest); err != nil {
			return err
		}
	}

	// Lock rewrite: only when explicitly requested (nil-vs-empty matters: an
	// empty non-nil slice clears the column, nil leaves it).
	if st.SetLock {
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE order_record SET lock = ? WHERE id = ?`,
			nullableBlob(st.Lock), orderID,
		); err != nil {
			return fmt.Errorf("store: settlement lock: %w", err)
		}
	}

	// Remaining open quantity: the caller carries the report's LeavesQty; an
	// empty value leaves the column untouched.
	if st.Leaves != "" {
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE order_record SET leaves_quantity = ? WHERE id = ?`,
			st.Leaves, orderID,
		); err != nil {
			return fmt.Errorf("store: settlement leaves: %w", err)
		}
	}

	// Status advance last; guarded only when AllowedFrom is set.
	if err := guardedOrderStatus(
		ctx, tx, orderID, st.Order, st.OrderStatus, st.AllowedFrom,
	); err != nil {
		return err
	}

	return nil
}

// guardedOrderStatus advances an order's status inside tx, addressing it by its
// already-resolved surrogate id. When allowedFrom is non-empty the UPDATE only
// matches rows already in one of those statuses; a 0-rows result then means
// either the order is missing (domain.ErrNotFound) or its current status is
// disallowed (domain.ErrConflict), distinguished by a follow-up SELECT in the
// same tx. When allowedFrom is empty the UPDATE is unguarded and 0 rows means a
// missing order. The order external id is carried for error messages only.
func guardedOrderStatus(
	ctx context.Context,
	tx *sql.Tx,
	orderID int64,
	order domain.ExternalID,
	status domain.OrderStatus,
	allowedFrom []domain.OrderStatus,
) error {
	args := []any{string(status), orderID}
	q := `UPDATE order_record SET status = ? WHERE id = ?`
	if len(allowedFrom) > 0 {
		placeholders := strings.TrimSuffix(strings.Repeat("?,", len(allowedFrom)), ",")
		q += fmt.Sprintf(` AND status IN (%s)`, placeholders)
		for _, s := range allowedFrom {
			args = append(args, string(s))
		}
	}
	res, err := tx.ExecContext(ctx, q, args...)
	if err != nil {
		return fmt.Errorf("store: resolve order %q status: %w", order.String(), err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return fmt.Errorf("store: resolve order %q status rows: %w", order.String(), err)
	}
	if n > 0 {
		return nil
	}
	// No row advanced: distinguish a missing order from a disallowed status.
	var cur string
	err = tx.QueryRowContext(
		ctx, `SELECT status FROM order_record WHERE id = ?`, orderID,
	).Scan(&cur)
	if errors.Is(err, sql.ErrNoRows) {
		return fmt.Errorf("order %q: %w", order.String(), domain.ErrNotFound)
	}
	if err != nil {
		return fmt.Errorf("store: resolve order %q status probe: %w", order.String(), err)
	}
	return fmt.Errorf(
		"store: resolve order %q: status %q: %w", order.String(), cur, domain.ErrConflict,
	)
}

func appendOrderEventReturningTx(
	ctx context.Context, tx *sql.Tx, orderID int64, ev domain.OrderEvent,
) (domain.OrderEvent, error) {
	principalID, err := resolveOptionalPrincipalID(ctx, tx, ev.Principal)
	if err != nil {
		return domain.OrderEvent{}, err
	}
	xid, err := newExternalID()
	if err != nil {
		return domain.OrderEvent{}, err
	}
	at := nowStr()
	payloadJSON, err := json.Marshal(ev.Payload)
	if err != nil {
		return domain.OrderEvent{}, fmt.Errorf("store: marshal event payload: %w", err)
	}
	if _, err := tx.ExecContext(
		ctx,
		`INSERT INTO order_event
		 (external_id, order_id, principal_id, at, type, source, payload)
		 VALUES (?, ?, ?, ?, ?, ?, ?)`,
		xid.Bytes(), orderID, principalID, at,
		string(ev.Type), string(ev.Source), string(payloadJSON),
	); err != nil {
		return domain.OrderEvent{}, fmt.Errorf("store: append order event: %w", err)
	}
	ev.ExternalID = xid
	ev.At = mustParseTime(at)
	return ev, nil
}

func attestOrderEventTx(
	ctx context.Context,
	tx *sql.Tx,
	event domain.OrderEvent,
	attest fwstore.EventAttestor,
) error {
	if attest == nil {
		return nil
	}
	att, ok, err := attest(ctx, event)
	if err != nil {
		return err
	}
	if !ok {
		return fmt.Errorf(
			"store: event %s has no attestation payload: %w",
			event.Type, domain.ErrInvalid,
		)
	}
	return putEventAttestationTx(ctx, tx, event.ExternalID, att)
}

// settleBalanceTx applies one per-asset fill outcome inside tx. Available,
// held, and incoming are independent optional engine-returned absolutes; an
// absent result preserves the prior value. Realized P&L is accumulated from the
// engine delta. The balance table is owned by another store group; this method
// touches it with direct SQL (never the public balance methods) to keep the
// whole settlement atomic.
func settleBalanceTx(
	ctx context.Context,
	tx *sql.Tx,
	accountID int64,
	bal domain.BalanceSettlement,
) error {
	assetID, err := resolveAssetID(ctx, tx, bal.Asset)
	if err != nil {
		return err
	}
	var prevAvail, prevHeld, prevIncoming, prevRealized, prevAvgPx string
	err = tx.QueryRowContext(
		ctx,
		`SELECT available, held, incoming, realized_pnl, average_entry_price
		 FROM balance WHERE account_id = ? AND asset_id = ?`,
		accountID, assetID,
	).Scan(&prevAvail, &prevHeld, &prevIncoming, &prevRealized, &prevAvgPx)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return fmt.Errorf("store: settle balance %q read: %w", bal.Asset, err)
	}

	realized, err := domain.AddDecimals(prevRealized, bal.Outcome.RealizedPnlDelta)
	if err != nil {
		return fmt.Errorf("store: settle balance %q realized_pnl: %w", bal.Asset, err)
	}
	available := settleOrZero(settlementResultOrPrevious(bal.Outcome.BalanceResult, prevAvail))
	held := settleOrZero(settlementResultOrPrevious(bal.Outcome.HeldResult, prevHeld))
	incoming := settleOrZero(settlementResultOrPrevious(bal.Outcome.IncomingResult, prevIncoming))
	realized = settleOrZero(realized)
	if _, err := tx.ExecContext(
		ctx,
		`INSERT OR REPLACE INTO balance
		 (account_id, asset_id, available, held,
		  incoming, realized_pnl, average_entry_price, updated_at)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
		accountID, assetID,
		available, held, incoming, realized, prevAvgPx,
		nowStr(),
	); err != nil {
		return fmt.Errorf("store: settle balance %q write: %w", bal.Asset, err)
	}
	if err := pruneEmptySettlementBalanceTx(
		ctx, tx, accountID, assetID, bal.Asset,
		available, held, incoming, realized, prevAvgPx,
	); err != nil {
		return err
	}
	return nil
}

func pruneEmptySettlementBalanceTx(
	ctx context.Context,
	tx *sql.Tx,
	accountID int64,
	assetID int64,
	asset string,
	available string,
	held string,
	incoming string,
	realized string,
	averageEntryPrice string,
) error {
	if !balanceAmountsEmpty(available, held, incoming, realized, averageEntryPrice) {
		return nil
	}
	if _, err := tx.ExecContext(
		ctx,
		`DELETE FROM balance WHERE account_id = ? AND asset_id = ?`,
		accountID, assetID,
	); err != nil {
		return fmt.Errorf("store: prune empty settlement balance %q: %w", asset, err)
	}
	return nil
}

func balanceAmountsEmpty(
	available string, held string, incoming string, realized string, averageEntryPrice string,
) bool {
	return decimalZeroOrEmpty(available) &&
		decimalZeroOrEmpty(held) &&
		decimalZeroOrEmpty(incoming) &&
		decimalZeroOrEmpty(realized) &&
		decimalZeroOrEmpty(averageEntryPrice)
}

func decimalZeroOrEmpty(value string) bool {
	if value == "" {
		return true
	}
	parsed, err := decimal.NewFromString(value)
	return err == nil && parsed.IsZero()
}

// --- Orders-group small helpers ---------------------------------------------

// lookupOrderID resolves an order's external id to its surrogate id, mapping a
// missing order onto domain.ErrNotFound. It is the orders-group analogue of the
// dictionary resolvers in sqlite.go; it joins the order's children and the
// settlement writes to the order without exposing the surrogate id.
func lookupOrderID(
	ctx context.Context, q sqlQueryer, id domain.ExternalID,
) (int64, error) {
	var orderID int64
	err := q.QueryRowContext(
		ctx, `SELECT id FROM order_record WHERE external_id = ?`, id.Bytes(),
	).Scan(&orderID)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, fmt.Errorf("order %q: %w", id.String(), domain.ErrNotFound)
	}
	if err != nil {
		return 0, fmt.Errorf("store: resolve order %q: %w", id.String(), err)
	}
	return orderID, nil
}

// lookupOrderEventID resolves an event's external id to its surrogate id,
// mapping a missing event onto domain.ErrNotFound. It is the analogue of
// lookupOrderID for the event stream; it keys the 1:1 attestation onto the event
// without exposing the surrogate id.
func lookupOrderEventID(
	ctx context.Context, q sqlQueryer, id domain.ExternalID,
) (int64, error) {
	var eventID int64
	err := q.QueryRowContext(
		ctx, `SELECT id FROM order_event WHERE external_id = ?`, id.Bytes(),
	).Scan(&eventID)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, fmt.Errorf("order event %q: %w", id.String(), domain.ErrNotFound)
	}
	if err != nil {
		return 0, fmt.Errorf("store: resolve order event %q: %w", id.String(), err)
	}
	return eventID, nil
}

// nullableBlob maps a nil byte slice to a NULL column value and a non-nil slice
// (including an empty one) to itself, so the lock column distinguishes "no lock"
// (NULL) from a present-but-empty serialized lock.
func nullableBlob(b []byte) any {
	if b == nil {
		return nil
	}
	return b
}

// mustParseTime parses an RFC3339Nano string the store itself just formatted via
// nowStr; the format is guaranteed, so a parse error is impossible and the zero
// time is returned defensively rather than panicking on the write path.
func mustParseTime(s string) time.Time {
	t, _ := time.Parse(time.RFC3339Nano, s)
	return t
}

// settleOrZero maps an empty amount string to "0" so a balance column is never
// written empty.
func settleOrZero(s string) string {
	if s == "" {
		return "0"
	}
	return s
}

func settlementResultOrPrevious(next, prev string) string {
	if next != "" {
		return next
	}
	return prev
}
