// PutEventAttestation stamps the attestation envelope onto the order-history
// event addressed by external id, write-once: it inserts the 1:1
// event_attestation row only when the event carries none yet (only event_id
// conflicts are ignored), so a retry or a later write never clobbers an
// already-issued envelope. An already-stamped event is a no-op; a missing event
// returns domain.ErrNotFound so callers cannot silently commit an unsigned
// event.
func (r *realmStore) PutEventAttestation(
	ctx context.Context, eventID domain.ExternalID, att domain.EventAttestation,
) error {
	db, err := r.db()
	if err != nil {
		return err
	}
	return putEventAttestationTx(ctx, db, eventID, att)
}

func putEventAttestationTx(
	ctx context.Context,
	q sqlReadWriter,
	eventID domain.ExternalID,
	att domain.EventAttestation,
) error {
	surrogate, err := lookupOrderEventID(ctx, q, eventID)
	if err != nil {
		return err
	}
	var signingKeyID sql.NullInt64
	if att.KeyID != "" {
		id, err := resolveSigningKeyID(ctx, q, att.KeyID)
		if err != nil {
			return err
		}
		signingKeyID = sql.NullInt64{Int64: id, Valid: true}
	}
	if _, err := q.ExecContext(
		ctx,
		`INSERT INTO event_attestation
		 (event_id, token, signing_key_id, alg, request_type, mode, issued_at)
		 VALUES (?, ?, ?, ?, ?, ?, ?)
		 ON CONFLICT(event_id) DO NOTHING`,
		surrogate, att.Token, signingKeyID, att.Alg, string(att.RequestType),
		att.Mode, att.IssuedAt,
	); err != nil {
		return fmt.Errorf("store: put event attestation: %w", err)
	}
	return nil
}

// GetOrder returns the order addressed by external id together with its events
// (each carrying its 1:1 signed attestation when one was issued) and trades.
// Returns domain.ErrNotFound when the order is absent.
//
// Each event's attestation is persisted in event_attestation (written by
// PutEventAttestation, write-once) and folded into OrderEvent.Attestation by the
// event read (nil when the event is unattested), so a caller presenting an order
// gets every event's envelope metadata without a second round-trip.
func (r *realmStore) GetOrder(
	ctx context.Context, id domain.ExternalID,
) (domain.OrderDetail, error) {
	db, err := r.db()
	if err != nil {
		return domain.OrderDetail{}, err
	}
	row := db.QueryRowContext(ctx, orderSelect+` WHERE o.external_id = ?`, id.Bytes())
	o, err := scanOrderRow(row)
	if errors.Is(err, sql.ErrNoRows) {
		return domain.OrderDetail{}, fmt.Errorf("order %q: %w", id.String(), domain.ErrNotFound)
	}
	if err != nil {
		return domain.OrderDetail{}, fmt.Errorf("store: get order: %w", err)
	}

	events, err := r.ListOrderEvents(ctx, id)
	if err != nil {
		return domain.OrderDetail{}, err
	}
	trades, err := r.listTradesByOrder(ctx, id)
	if err != nil {
		return domain.OrderDetail{}, err
	}
	o.CommissionSubtotals, err = commissionSubtotals(trades)
	if err != nil {
		return domain.OrderDetail{}, err
	}
	return domain.OrderDetail{Order: o, Events: events, Trades: trades}, nil
}

// ListOrders returns the most recent n orders for an account, newest first. An
// empty account spans every account; an empty source spans every source; a
// non-positive n returns an empty slice.
func (r *realmStore) ListOrders(
	ctx context.Context, account domain.AccountID, source domain.Source, n int,
) ([]domain.Order, error) {
	if n <= 0 {
		return make([]domain.Order, 0), nil
	}
	return r.listOrders(ctx, account, source, n)
}

// ListAllOrders returns every order for an account, newest first. It is used by
// exports that must not inherit UI display limits.
func (r *realmStore) ListAllOrders(
	ctx context.Context, account domain.AccountID, source domain.Source,
) ([]domain.Order, error) {
	return r.listOrders(ctx, account, source, 0)
}

// ListOrderRows returns orders matching filter, with total count before paging.
func (r *realmStore) ListOrderRows(
	ctx context.Context, filter fwstore.OrderListFilter,
) (fwstore.OrderListPage, error) {
	where, args := orderListWhere(filter)
	countQuery := `SELECT COUNT(*)
FROM order_record o
JOIN account a       ON a.id = o.account_id
JOIN asset ba        ON ba.id = o.base_asset_id
JOIN asset qa        ON qa.id = o.quote_asset_id
LEFT JOIN principal p ON p.id = o.principal_id` + where
	db, err := r.db()
	if err != nil {
		return fwstore.OrderListPage{}, err
	}
	var total int
	if err := db.QueryRowContext(ctx, countQuery, args...).Scan(&total); err != nil {
		return fwstore.OrderListPage{}, fmt.Errorf("store: count order rows: %w", err)
	}

	queryArgs := append([]any{}, args...)
	query := orderListSelect + where + orderListOrderBy(filter.Sort)
	if filter.Page.Limit > 0 {
		query += ` LIMIT ? OFFSET ?`
		queryArgs = append(queryArgs, filter.Page.Limit, max(filter.Page.Offset, 0))
	}
	rows, err := db.QueryContext(ctx, query, queryArgs...)
	if err != nil {
		return fwstore.OrderListPage{}, fmt.Errorf("store: list order rows: %w", err)
	}
	defer func() { _ = rows.Close() }()

	result := make([]fwstore.OrderListRow, 0)
	orderIDs := make([]domain.ExternalID, 0)
	for rows.Next() {
		o, signed, err := scanOrderListRow(rows)
		if err != nil {
			return fwstore.OrderListPage{}, err
		}
		result = append(result, fwstore.OrderListRow{Order: o, Signed: signed})
		orderIDs = append(orderIDs, o.ExternalID)
	}
	if err := rows.Err(); err != nil {
		return fwstore.OrderListPage{}, fmt.Errorf("store: iterate order rows: %w", err)
	}
	subtotals, err := commissionSubtotalsByOrder(ctx, db, orderIDs)
	if err != nil {
		return fwstore.OrderListPage{}, err
	}
	for i := range result {
		result[i].Order.CommissionSubtotals = subtotals[result[i].Order.ExternalID]
	}
	return fwstore.OrderListPage{Rows: result, Total: total}, nil
}

// listOrders is the shared order-list query: it filters by the non-empty
// account and source, orders newest first by (at, id) per the §9 index, and
// applies the optional positive limit.
func (r *realmStore) listOrders(
	ctx context.Context, account domain.AccountID, source domain.Source, limit int,
) ([]domain.Order, error) {
	page, err := r.ListOrderRows(ctx, fwstore.OrderListFilter{
		Account: account,
		Source:  source,
		Sort:    fwstore.SortSpec{Column: "at", Descending: true},
		Page:    fwstore.PageSpec{Limit: limit},
	})
	if err != nil {
		return nil, err
	}
	result := make([]domain.Order, 0, len(page.Rows))
	for _, row := range page.Rows {
		result = append(result, row.Order)
	}
	return result, nil
}

func orderListWhere(filter fwstore.OrderListFilter) (string, []any) {
	clauses := make([]string, 0)
	args := make([]any, 0)
	if filter.Account != "" {
		clauses = append(clauses, "a.code = ?")
		args = append(args, filter.Account.String())
	}
	if filter.Source != "" {
		clauses = append(clauses, "o.source = ?")
		args = append(args, string(filter.Source))
	}
	if filter.Side != nil {
		clauses = append(clauses, "o.side = ?")
		args = append(args, string(*filter.Side))
	}
	if len(filter.Status) > 0 {
		placeholders := strings.TrimRight(strings.Repeat("?,", len(filter.Status)), ",")
		clauses = append(clauses, "o.status IN ("+placeholders+")")
		for _, status := range filter.Status {
			args = append(args, string(status))
		}
	}
	appendMatcher(&clauses, &args, "ba.code", filter.BaseAsset)
	appendMatcher(&clauses, &args, "qa.code", filter.QuoteAsset)
	appendDecimalRangeFilter(&clauses, &args, "o.amount_value", filter.Amount)
	appendDecimalRangeFilter(&clauses, &args, "o.price", filter.Price)
	appendTimeRangeFilter(&clauses, &args, "o.at", filter.At)
	if len(clauses) == 0 {
		return "", args
	}
	return "\nWHERE " + strings.Join(clauses, " AND "), args
}

func orderListOrderBy(sort fwstore.SortSpec) string {
	columns := map[string]string{
		"account":     "a.code",
		"at":          "o.at",
		"baseAsset":   "ba.code",
		"price":       "o.price",
		"quoteAsset":  "qa.code",
		"side":        "o.side",
		"source":      "o.source",
		"status":      "o.status",
		"amountValue": "o.amount_value",
	}
	column := columns[sort.Column]
	if column == "" {
		column = "o.at"
		sort.Descending = true
	}
	direction := "ASC"
	tieDirection := "ASC"
	if sort.Descending {
		direction = "DESC"
		tieDirection = "DESC"
	}
	return "\nORDER BY " + column + " " + direction + ", o.id " + tieDirection
}

