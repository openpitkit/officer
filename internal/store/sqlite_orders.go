// Orders group of the SQLite store: orders and their 1:1 signed approval, the
// immutable order-event stream, per-fill trades ("reports"), order counts and
// the atomic fill/settlement write. Every record here is machine-generated and
// addressed by its opaque external id; the surrogate key joins rows internally
// and never crosses the interface boundary. Account, asset and principal
// references are resolved by code on write and surfaced as code on read, so a
// surrogate id never leaks. The SDK-serialized reservation lock is persisted
// verbatim as a BLOB and read back byte-identical; this package never decodes it.

package store

import (
	"context"
	"database/sql"
	"encoding/json"
	"errors"
	"fmt"
	"strings"
	"time"

	"go.openpit.dev/officer/framework/domain"
)

// --- Orders -----------------------------------------------------------------

// orderSelect is the shared projection for order reads. The JOINs surface the
// account, base/quote asset and (optional) principal as their codes so the
// surrogate ids never leave the store; the LEFT JOIN on principals yields NULL
// when the reference was cleared or never set. The lock BLOB is read back
// verbatim into the domain []byte.
const orderSelect = `
SELECT o.external_id, a.code, ba.code, qa.code, p.code,
       o.at, o.source, o.side, o.amount_kind, o.amount_value,
       o.price, o.status, o.lock
FROM orders o
JOIN accounts a       ON a.id = o.account_id
JOIN assets ba        ON ba.id = o.base_asset_id
JOIN assets qa        ON qa.id = o.quote_asset_id
LEFT JOIN principals p ON p.id = o.principal_id`

// CreateOrder inserts a new order and its submission time. It resolves the
// account and both assets by code to their surrogate ids and the optional
// principal to a nullable id, then persists the SDK-serialized lock blob
// verbatim. A caller-supplied o.ExternalID is used verbatim so the operator owns
// the handle; a zero id is generated by the connector. A duplicate supplied id
// is rejected with domain.ErrAlreadyExists (the external_id UNIQUE constraint,
// no pre-insert probe). It returns the order with ExternalID and At populated;
// the surrogate id is never surfaced.
func (r *realmStore) CreateOrder(
	ctx context.Context, o domain.Order,
) (domain.Order, error) {
	accountID, err := resolveAccountID(ctx, r.db(), o.Account)
	if err != nil {
		return o, err
	}
	baseID, err := resolveAssetID(ctx, r.db(), o.BaseAsset)
	if err != nil {
		return o, err
	}
	quoteID, err := resolveAssetID(ctx, r.db(), o.QuoteAsset)
	if err != nil {
		return o, err
	}
	principalID, err := resolveOptionalPrincipalID(ctx, r.db(), o.Principal)
	if err != nil {
		return o, err
	}
	xid, err := externalIDForInsert(o.ExternalID)
	if err != nil {
		return o, err
	}
	at := nowStr()
	if _, err := r.db().ExecContext(
		ctx,
		`INSERT INTO orders
		 (external_id, account_id, base_asset_id, quote_asset_id, principal_id,
		  at, source, side, amount_kind, amount_value, price, status, lock)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		xid.Bytes(), accountID, baseID, quoteID, principalID,
		at, string(o.Source), string(o.Side), string(o.AmountKind),
		o.AmountValue, o.Price, string(o.Status), nullableBlob(o.Lock),
	); err != nil {
		if isSQLiteUnique(err) {
			return o, fmt.Errorf(
				"order %q: %w", xid.String(), domain.ErrAlreadyExists,
			)
		}
		return o, fmt.Errorf("store: create order: %w", err)
	}
	o.ExternalID = xid
	o.At = mustParseTime(at)
	return o, nil
}

// UpdateOrderStatus updates the status of the order addressed by external id.
func (r *realmStore) UpdateOrderStatus(
	ctx context.Context, id domain.ExternalID, status domain.OrderStatus,
) error {
	res, err := r.db().ExecContext(
		ctx,
		`UPDATE orders SET status = ? WHERE external_id = ?`,
		string(status), id.Bytes(),
	)
	if err != nil {
		return fmt.Errorf("store: update order status: %w", err)
	}
	return notFoundIfNoRows(res, "order", id.String())
}

// SetOrderLock replaces the persisted SDK-serialized lock blob of the order
// addressed by external id, writing the bytes verbatim. A nil lock clears the
// column.
func (r *realmStore) SetOrderLock(
	ctx context.Context, id domain.ExternalID, lock []byte,
) error {
	res, err := r.db().ExecContext(
		ctx,
		`UPDATE orders SET lock = ? WHERE external_id = ?`,
		nullableBlob(lock), id.Bytes(),
	)
	if err != nil {
		return fmt.Errorf("store: set order lock: %w", err)
	}
	return notFoundIfNoRows(res, "order", id.String())
}

// PutOrderApproval stamps the signed approval envelope onto the order addressed
// by external id, write-once: it inserts the 1:1 order_approvals row only when
// the order carries none yet (INSERT OR IGNORE on the order_id primary key), so
// a retry or a later write never clobbers an already-issued envelope. A no-op
// (already stamped, or missing order) is not an error: the envelope is
// best-effort and the order is the durable trail.
func (r *realmStore) PutOrderApproval(
	ctx context.Context, id domain.ExternalID, env domain.OrderApproval,
) error {
	orderID, err := lookupOrderID(ctx, r.db(), id)
	if err != nil {
		if errors.Is(err, domain.ErrNotFound) {
			// Missing order is a tolerated no-op, not an error.
			return nil
		}
		return err
	}
	signingKeyID, err := resolveSigningKeyID(ctx, r.db(), env.KeyID)
	if err != nil {
		return err
	}
	if _, err := r.db().ExecContext(
		ctx,
		`INSERT OR IGNORE INTO order_approvals
		 (order_id, token, signing_key_id, alg, mode, issued_at, expires_at)
		 VALUES (?, ?, ?, ?, ?, ?, ?)`,
		orderID, env.Token, signingKeyID, env.Alg, env.Mode,
		env.IssuedAt, env.ExpiresAt,
	); err != nil {
		return fmt.Errorf("store: put order approval: %w", err)
	}
	return nil
}

// GetOrder returns the order addressed by external id together with its events,
// trades, and its 1:1 signed approval when one was issued. Returns
// domain.ErrNotFound when the order is absent.
//
// The order's signed approval is persisted in order_approvals (written by
// PutOrderApproval, write-once). It is read back through the getOrderApproval
// seam and folded into OrderDetail.Approval (nil when the order is unsigned), so
// a caller presenting an order gets its envelope metadata without a second
// round-trip.
func (r *realmStore) GetOrder(
	ctx context.Context, id domain.ExternalID,
) (domain.OrderDetail, error) {
	row := r.db().QueryRowContext(ctx, orderSelect+` WHERE o.external_id = ?`, id.Bytes())
	o, err := scanOrderRow(row)
	if errors.Is(err, sql.ErrNoRows) {
		return domain.OrderDetail{}, fmt.Errorf("order %q: %w", id.String(), domain.ErrNotFound)
	}
	if err != nil {
		return domain.OrderDetail{}, fmt.Errorf("store: get order: %w", err)
	}

	events, err := r.ListOrderEvents(ctx, id)
	if err != nil {
		return domain.OrderDetail{}, err
	}
	trades, err := r.listTradesByOrder(ctx, id)
	if err != nil {
		return domain.OrderDetail{}, err
	}
	detail := domain.OrderDetail{Order: o, Events: events, Trades: trades}
	if env, ok, aerr := r.getOrderApproval(ctx, id); aerr != nil {
		return domain.OrderDetail{}, aerr
	} else if ok {
		detail.Approval = &env
	}
	return detail, nil
}

