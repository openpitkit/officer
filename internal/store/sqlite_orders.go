// listTrades is the shared trade-list query: it filters by the non-empty account
// and source, orders newest first by (at, id) per the §9 index, and applies the
// optional positive limit.
func (r *realmStore) listTrades(
	ctx context.Context, account domain.AccountID, source domain.Source, limit int,
) ([]domain.Trade, error) {
	q := tradeSelect + ` WHERE 1 = 1`
	args := make([]any, 0, 3)
	if account != "" {
		q += ` AND a.code = ?`
		args = append(args, account.String())
	}
	if source != "" {
		q += ` AND t.source = ?`
		args = append(args, string(source))
	}
	q += ` ORDER BY t.at DESC, t.id DESC`
	if limit > 0 {
		q += ` LIMIT ?`
		args = append(args, limit)
	}

	rows, err := r.db().QueryContext(ctx, q, args...)
	if err != nil {
		return nil, fmt.Errorf("store: list trades: %w", err)
	}
	defer func() { _ = rows.Close() }()
	return scanTrades(rows)
}

// listTradesByOrder returns all trades for one order (addressed by its external
// id), oldest first by (at, id). It backs GetOrder's trade list.
func (r *realmStore) listTradesByOrder(
	ctx context.Context, order domain.ExternalID,
) ([]domain.Trade, error) {
	rows, err := r.db().QueryContext(
		ctx,
		tradeSelect+` WHERE o.external_id = ? ORDER BY t.at ASC, t.id ASC`,
		order.Bytes(),
	)
	if err != nil {
		return nil, fmt.Errorf("store: list trades by order: %w", err)
	}
	defer func() { _ = rows.Close() }()
	return scanTrades(rows)
}

func scanTrades(rows *sql.Rows) ([]domain.Trade, error) {
	result := make([]domain.Trade, 0)
	for rows.Next() {
		tr, err := scanTrade(rows)
		if err != nil {
			return nil, err
		}
		result = append(result, tr)
	}
	if err := rows.Err(); err != nil {
		return nil, fmt.Errorf("store: iterate trades: %w", err)
	}
	return result, nil
}

func scanTrade(rows *sql.Rows) (domain.Trade, error) {
	var (
		tradeExtID, orderExtID                    []byte
		account                                   string
		baseAsset, quoteAsset                     string
		principal                                 sql.NullString
		at, source, side, quantity, price, lockPx string
	)
	if err := rows.Scan(
		&tradeExtID, &orderExtID, &account, &baseAsset, &quoteAsset, &principal,
		&at, &source, &side, &quantity, &price, &lockPx,
	); err != nil {
		return domain.Trade{}, fmt.Errorf("store: scan trade: %w", err)
	}
	tradeXID, err := domain.ExternalIDFromBytes(tradeExtID)
	if err != nil {
		return domain.Trade{}, fmt.Errorf("store: decode trade external id: %w", err)
	}
	orderXID, err := domain.ExternalIDFromBytes(orderExtID)
	if err != nil {
		return domain.Trade{}, fmt.Errorf("store: decode trade order external id: %w", err)
	}
	parsedAt, err := time.Parse(time.RFC3339Nano, at)
	if err != nil {
		return domain.Trade{}, fmt.Errorf("store: parse trade at %q: %w", at, err)
	}
	return domain.Trade{
		ExternalID: tradeXID,
		Order:      orderXID,
		Account:    domain.AccountID(account),
		BaseAsset:  baseAsset,
		QuoteAsset: quoteAsset,
		Principal:  principal.String,
		At:         parsedAt,
		Source:     domain.Source(source),
		Side:       domain.OrderSide(side),
		Quantity:   quantity,
		Price:      price,
		LockPrice:  lockPx,
	}, nil
}

// --- Settlement -------------------------------------------------------------

// RecordOrderSettlement persists one fill/settlement atomically in a single
// transaction: per-asset balances (realized P&L delta-accumulated inside the
// tx), the engine-applied account blocks, the optional trade, the fill event(s),
// the optional lock rewrite and the order status advance commit or roll back
// together. A zero st.Order is an in-memory-only hold with no order row: the
// order/event/lock writes are skipped and only the balance and block effects
// run. When AllowedFrom is non-empty the status UPDATE is guarded and a
// disallowed current status yields domain.ErrConflict with nothing written;
// otherwise a missing order yields domain.ErrNotFound. The block-audit row is
// NOT part of this tx; callers write it separately after a successful commit.
func (r *realmStore) RecordOrderSettlement(
	ctx context.Context, st domain.OrderSettlement,
) error {
	tx, err := r.db().BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("store: begin record_order_settlement: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	// Resolve the settling account once; balances and blocks reuse it. The
	// account is the fill's account, always present on a settlement.
	accountID, err := resolveAccountID(ctx, tx, st.Account)
	if err != nil {
		return err
	}

	// Per-asset balances: read-modify-write inside the tx so the realized-P&L
	// accumulate is consistent under the tx snapshot (SQLite serializes writers).
	for _, bal := range st.Balances {
		if err := settleBalanceTx(ctx, tx, accountID, bal); err != nil {
			return err
		}
	}

	// Mirror engine-applied account blocks (the block UPDATE only; the audit row
	// stays a post-commit write owned by the caller). A block names its own
	// account, which may differ from the fill account in principle, so resolve it.
	for _, blk := range st.Blocks {
		blkAccountID, err := resolveAccountID(ctx, tx, blk.Account)
		if err != nil {
			return err
		}
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE accounts SET blocked = ?, block_reason = ? WHERE id = ?`,
			true, blk.Reason, blkAccountID,
		); err != nil {
			return fmt.Errorf("store: settlement mirror block %q: %w", blk.Account, err)
		}
	}

	// Trade row.
	if st.Trade != nil {
		if _, _, err := r.insertTrade(ctx, tx, *st.Trade); err != nil {
			return err
		}
	}

	// The remaining writes touch the order row; an in-memory-only hold (zero
	// Order) carries no order row, so skip them and only the balance/block
	// effects above run.
	if st.Order.IsZero() {
		if err := tx.Commit(); err != nil {
			return fmt.Errorf("store: commit record_order_settlement: %w", err)
		}
		return nil
	}

	// Resolve the order surrogate id once; events, the optional lock rewrite and
	// the status advance all reuse it.
	orderID, err := lookupOrderID(ctx, tx, st.Order)
	if err != nil {
		return err
	}

	// Fill event(s).
	for _, ev := range st.Events {
		if err := appendOrderEventTx(ctx, tx, orderID, ev); err != nil {
			return err
		}
	}

	// Lock rewrite: only when explicitly requested (nil-vs-empty matters: an
	// empty non-nil slice clears the column, nil leaves it).
	if st.SetLock {
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE orders SET lock = ? WHERE id = ?`,
			nullableBlob(st.Lock), orderID,
		); err != nil {
			return fmt.Errorf("store: settlement lock: %w", err)
		}
	}

	// Status advance last; guarded only when AllowedFrom is set.
	if err := guardedOrderStatus(
		ctx, tx, orderID, st.Order, st.OrderStatus, st.AllowedFrom,
	); err != nil {
		return err
	}

	if err := tx.Commit(); err != nil {
		return fmt.Errorf("store: commit record_order_settlement: %w", err)
	}
	return nil
}

// guardedOrderStatus advances an order's status inside tx, addressing it by its
// already-resolved surrogate id. When allowedFrom is non-empty the UPDATE only
// matches rows already in one of those statuses; a 0-rows result then means
// either the order is missing (domain.ErrNotFound) or its current status is
// disallowed (domain.ErrConflict), distinguished by a follow-up SELECT in the
// same tx. When allowedFrom is empty the UPDATE is unguarded and 0 rows means a
// missing order. The order external id is carried for error messages only.
func guardedOrderStatus(
	ctx context.Context,
	tx *sql.Tx,
	orderID int64,
	order domain.ExternalID,
	status domain.OrderStatus,
	allowedFrom []domain.OrderStatus,
) error {
	args := []any{string(status), orderID}
	q := `UPDATE orders SET status = ? WHERE id = ?`
	if len(allowedFrom) > 0 {
		placeholders := strings.TrimSuffix(strings.Repeat("?,", len(allowedFrom)), ",")
		q += fmt.Sprintf(` AND status IN (%s)`, placeholders)
		for _, s := range allowedFrom {
			args = append(args, string(s))
		}
	}
	res, err := tx.ExecContext(ctx, q, args...)
	if err != nil {
		return fmt.Errorf("store: resolve order %q status: %w", order.String(), err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return fmt.Errorf("store: resolve order %q status rows: %w", order.String(), err)
	}
	if n > 0 {
		return nil
	}
	// No row advanced: distinguish a missing order from a disallowed status.
	var cur string
	err = tx.QueryRowContext(
		ctx, `SELECT status FROM orders WHERE id = ?`, orderID,
	).Scan(&cur)
	if errors.Is(err, sql.ErrNoRows) {
		return fmt.Errorf("order %q: %w", order.String(), domain.ErrNotFound)
	}
	if err != nil {
		return fmt.Errorf("store: resolve order %q status probe: %w", order.String(), err)
	}
	return fmt.Errorf(
		"store: resolve order %q: status %q: %w", order.String(), cur, domain.ErrConflict,
	)
}

// appendOrderEventTx inserts one order event inside tx against the already-
// resolved order surrogate id, mirroring AppendOrderEvent's external-id, payload
// and timestamp handling.
func appendOrderEventTx(
	ctx context.Context, tx *sql.Tx, orderID int64, ev domain.OrderEvent,
) error {
	principalID, err := resolveOptionalPrincipalID(ctx, tx, ev.Principal)
	if err != nil {
		return err
	}
	xid, err := newExternalID()
	if err != nil {
		return err
	}
	payloadJSON, err := json.Marshal(ev.Payload)
	if err != nil {
		return fmt.Errorf("store: marshal event payload: %w", err)
	}
	if _, err := tx.ExecContext(
		ctx,
		`INSERT INTO order_events
		 (external_id, order_id, principal_id, at, type, source, payload)
		 VALUES (?, ?, ?, ?, ?, ?, ?)`,
		xid.Bytes(), orderID, principalID, nowStr(),
		string(ev.Type), string(ev.Source), string(payloadJSON),
	); err != nil {
		return fmt.Errorf("store: append order event: %w", err)
	}
	return nil
}

// settleBalanceTx applies one per-asset fill outcome inside tx. It resolves the
// asset code to its surrogate id, reads the prior row (zero-value on absence),
// accumulates realized P&L by delta, takes available/held/incoming from the
// outcome's *Result with the prior value carried forward when a result is empty,
// carries average_entry_price forward (a fill does not restate it) and writes
// the row back. This is the node's former read-modify-write fill persistence,
// moved inside the tx so the accumulate cannot lose an update. The balances
// table is owned by another store group; this method touches it with direct SQL
// (never the public balance methods) to keep the whole settlement atomic.
func settleBalanceTx(
	ctx context.Context,
	tx *sql.Tx,
	accountID int64,
	bal domain.BalanceSettlement,
) error {
	assetID, err := resolveAssetID(ctx, tx, bal.Asset)
	if err != nil {
		return err
	}
	var prevAvail, prevHeld, prevIncoming, prevRealized, prevAvgPx string
	err = tx.QueryRowContext(
		ctx,
		`SELECT available, held, incoming, realized_pnl, average_entry_price
		 FROM balances WHERE account_id = ? AND asset_id = ?`,
		accountID, assetID,
	).Scan(&prevAvail, &prevHeld, &prevIncoming, &prevRealized, &prevAvgPx)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return fmt.Errorf("store: settle balance %q read: %w", bal.Asset, err)
	}

	realized, err := domain.AddDecimals(prevRealized, bal.Outcome.RealizedPnlDelta)
	if err != nil {
		return fmt.Errorf("store: settle balance %q realized_pnl: %w", bal.Asset, err)
	}
	if _, err := tx.ExecContext(
		ctx,
		`INSERT OR REPLACE INTO balances
		 (account_id, asset_id, available, held, incoming, realized_pnl,
		  average_entry_price, updated_at)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?)`,
		accountID, assetID,
		settleOrZero(settlePick(bal.Outcome.BalanceResult, prevAvail)),
		settleOrZero(settlePick(bal.Outcome.HeldResult, prevHeld)),
		settleOrZero(settlePick(bal.Outcome.IncomingResult, prevIncoming)),
		settleOrZero(realized),
		prevAvgPx,
		nowStr(),
	); err != nil {
		return fmt.Errorf("store: settle balance %q write: %w", bal.Asset, err)
	}
	return nil
}

// --- Orders-group small helpers ---------------------------------------------

// lookupOrderID resolves an order's external id to its surrogate id, mapping a
// missing order onto domain.ErrNotFound. It is the orders-group analogue of the
// dictionary resolvers in sqlite.go; it joins the order's children and the
// settlement writes to the order without exposing the surrogate id.
func lookupOrderID(
	ctx context.Context, q sqlQueryer, id domain.ExternalID,
) (int64, error) {
	var orderID int64
	err := q.QueryRowContext(
		ctx, `SELECT id FROM orders WHERE external_id = ?`, id.Bytes(),
	).Scan(&orderID)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, fmt.Errorf("order %q: %w", id.String(), domain.ErrNotFound)
	}
	if err != nil {
		return 0, fmt.Errorf("store: resolve order %q: %w", id.String(), err)
	}
	return orderID, nil
}

// nullableBlob maps a nil byte slice to a NULL column value and a non-nil slice
// (including an empty one) to itself, so the lock column distinguishes "no lock"
// (NULL) from a present-but-empty serialized lock.
func nullableBlob(b []byte) any {
	if b == nil {
		return nil
	}
	return b
}

// mustParseTime parses an RFC3339Nano string the store itself just formatted via
// nowStr; the format is guaranteed, so a parse error is impossible and the zero
// time is returned defensively rather than panicking on the write path.
func mustParseTime(s string) time.Time {
	t, _ := time.Parse(time.RFC3339Nano, s)
	return t
}

// settlePick returns next when it is non-empty, otherwise the carried-forward
// prev. A fill outcome leaves a field's *Result empty when the fill did not move
// that field, so the prior stored value is retained.
func settlePick(next, prev string) string {
	if next != "" {
		return next
	}
	return prev
}

// settleOrZero maps an empty amount string to "0" so a balance column is never
// written empty.
func settleOrZero(s string) string {
	if s == "" {
		return "0"
	}
	return s
}
