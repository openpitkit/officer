// tradeSelect is the shared projection for trade reads. The order reference is
// surfaced outward as the order's external id (order_external_id); the surrogate
// order id never leaves the store. Account, both assets and the optional
// principal are surfaced as codes.
const tradeSelect = `
SELECT t.external_id, o.external_id, a.code, ba.code, qa.code, p.code,
       t.at, t.source, t.side, t.quantity, t.price, t.lock_price,
       t.commission_amount, t.commission_currency
FROM trade t
JOIN order_record o          ON o.id = t.order_id
JOIN account a        ON a.id = t.account_id
JOIN asset ba         ON ba.id = t.base_asset_id
JOIN asset qa         ON qa.id = t.quote_asset_id
LEFT JOIN principal p ON p.id = t.principal_id`

// CreateTrade records a fill as a standalone trade row, assigning its external
// id and timestamp. It links to the originating order (surrogate id resolved
// from the order's external id), the account and both assets by code, and the
// optional principal.
func (r *realmStore) CreateTrade(
	ctx context.Context, t domain.Trade,
) (domain.Trade, error) {
	db, err := r.db()
	if err != nil {
		return domain.Trade{}, err
	}
	xid, at, err := r.insertTrade(ctx, db, t)
	if err != nil {
		return t, err
	}
	t.ExternalID = xid
	t.At = mustParseTime(at)
	return t, nil
}

// insertTrade resolves a trade's foreign keys and inserts the row through exec
// (a *sql.DB or *sql.Tx), returning the assigned external id and timestamp text.
// It is shared by CreateTrade and the settlement transaction so both write an
// identical row.
func (r *realmStore) insertTrade(
	ctx context.Context, exec interface {
		sqlQueryer
		sqlExecer
	}, t domain.Trade,
) (domain.ExternalID, string, error) {
	if err := validateCommission(t.Commission); err != nil {
		return domain.ExternalID(""), "", err
	}
	orderID, err := lookupOrderID(ctx, exec, t.Order)
	if err != nil {
		return domain.ExternalID(""), "", err
	}
	accountID, err := resolveAccountID(ctx, exec, t.Account)
	if err != nil {
		return domain.ExternalID(""), "", err
	}
	baseID, err := resolveAssetID(ctx, exec, t.BaseAsset)
	if err != nil {
		return domain.ExternalID(""), "", err
	}
	quoteID, err := resolveAssetID(ctx, exec, t.QuoteAsset)
	if err != nil {
		return domain.ExternalID(""), "", err
	}
	principalID, err := resolveOptionalPrincipalID(ctx, exec, t.Principal)
	if err != nil {
		return domain.ExternalID(""), "", err
	}
	xid, err := newExternalID()
	if err != nil {
		return domain.ExternalID(""), "", err
	}
	at := nowStr()
	if _, err := exec.ExecContext(
		ctx,
		`INSERT INTO trade
	 (external_id, order_id, account_id, base_asset_id, quote_asset_id,
	  principal_id, at, source, side, quantity, price, lock_price,
	  commission_amount, commission_currency)
	 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		xid.Bytes(), orderID, accountID, baseID, quoteID, principalID,
		at, string(t.Source), string(t.Side), t.Quantity, t.Price, t.LockPrice,
		commissionAmount(t.Commission), commissionCurrency(t.Commission),
	); err != nil {
		return domain.ExternalID(""), "", fmt.Errorf("store: create trade: %w", err)
	}
	return xid, at, nil
}

