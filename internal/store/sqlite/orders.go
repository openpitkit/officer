// --- Orders -----------------------------------------------------------------

// orderSelect is the shared projection for order reads. The JOINs surface the
// account, base/quote asset and (optional) principal as their codes so the
// surrogate ids never leave the store; the LEFT JOIN on principal yields NULL
// when the reference was cleared or never set. The lock BLOB is read back
// verbatim into the domain []byte.
const orderSelect = `
SELECT o.external_id, a.code, ba.code, qa.code, p.code,
       o.at, o.source_id, o.side_id, o.amount_kind_id, o.amount_value,
       o.leaves_quantity, o.price, o.status_id, o.drop_copy, o.lock
FROM order_record o
JOIN account a       ON a.id = o.account_id
JOIN asset ba        ON ba.id = o.base_asset_id
JOIN asset qa        ON qa.id = o.quote_asset_id
LEFT JOIN principal p ON p.id = o.principal_id`

// orderListSelect extends orderSelect with a "signed" rollup so the paged list
// view can report whether the order carries at least one Ed25519-signed event
// attestation without a second query per order. The correlated subquery is 1
// when any of the order's events has a signed attestation, else 0.
const orderListSelect = `
SELECT o.external_id, a.code, ba.code, qa.code, p.code,
       o.at, o.source_id, o.side_id, o.amount_kind_id, o.amount_value,
       o.leaves_quantity, o.price, o.status_id, o.drop_copy, o.lock,
       EXISTS (
           SELECT 1 FROM order_event e
           JOIN event_attestation ea ON ea.event_id = e.id
           WHERE e.order_id = o.id AND ea.alg_id = 1
       ) AS signed
FROM order_record o
JOIN account a       ON a.id = o.account_id
JOIN asset ba        ON ba.id = o.base_asset_id
JOIN asset qa        ON qa.id = o.quote_asset_id
LEFT JOIN principal p ON p.id = o.principal_id`

// CreateOrder inserts a new order and its submission time. It resolves the
// account and both assets by code to their surrogate ids and the optional
// principal to a nullable id, then persists the SDK-serialized lock blob
// verbatim. A caller-supplied o.ExternalID is used verbatim so the operator owns
// the handle; a zero id is generated by the connector. A duplicate supplied id
// is rejected with domain.ErrAlreadyExists (the external_id UNIQUE constraint,
// no pre-insert probe). It returns the order with ExternalID and At populated;
// the surrogate id is never surfaced.
func (r *realmStore) CreateOrder(
	ctx context.Context, o domain.Order,
) (domain.Order, error) {
	db, err := r.db()
	if err != nil {
		return domain.Order{}, err
	}
	dictionaries, err := r.dictionaries()
	if err != nil {
		return domain.Order{}, err
	}
	return createOrderTx(ctx, dictionaries, db, o)
}

func createOrderTx(
	ctx context.Context,
	dictionaries *enumDictionaries,
	q sqlReadWriter,
	o domain.Order,
) (domain.Order, error) {
	accountID, err := resolveAccountID(ctx, q, o.Account)
	if err != nil {
		return o, err
	}
	baseID, err := resolveAssetID(ctx, q, o.BaseAsset)
	if err != nil {
		return o, err
	}
	quoteID, err := resolveAssetID(ctx, q, o.QuoteAsset)
	if err != nil {
		return o, err
	}
	principalID, err := resolveOptionalPrincipalID(ctx, q, o.Principal)
	if err != nil {
		return o, err
	}
	o.Source = storedSource(o.Source)
	sourceID, err := dictionaries.id(sourceKindTable, "source", string(o.Source))
	if err != nil {
		return o, err
	}
	sideID, err := dictionaries.id(orderSideTable, "order side", string(o.Side))
	if err != nil {
		return o, err
	}
	amountKindID, err := dictionaries.id(
		orderAmountKindTable, "order amount kind", string(o.AmountKind),
	)
	if err != nil {
		return o, err
	}
	statusID, err := dictionaries.id(orderStatusTable, "order status", string(o.Status))
	if err != nil {
		return o, err
	}
	xid, err := externalIDForInsert(o.ExternalID)
	if err != nil {
		return o, err
	}
	at := nowStr()
	if _, err := q.ExecContext(
		ctx,
		`INSERT INTO order_record
		 (external_id, account_id, base_asset_id, quote_asset_id, principal_id,
		  at, source_id, side_id, amount_kind_id, amount_value,
		  leaves_quantity, price, status_id, drop_copy, lock)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		xid.Bytes(), accountID, baseID, quoteID, principalID,
		at, sourceID, sideID, amountKindID,
		o.AmountValue, o.Leaves, o.Price,
		statusID, o.DropCopy, nullableBlob(o.Lock),
	); err != nil {
		if isSQLiteUnique(err) {
			return o, fmt.Errorf(
				"order %q: %w", xid.String(), domain.ErrAlreadyExists,
			)
		}
		return o, fmt.Errorf("store: create order: %w", err)
	}
	o.ExternalID = xid
	o.At = mustParseTime(at)
	return o, nil
}

