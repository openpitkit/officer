func tradeFromScanned(
	dictionaries *enumDictionaries,
	tradeExtID []byte,
	orderExtID []byte,
	account string,
	baseAsset string,
	quoteAsset string,
	principal sql.NullString,
	at string,
	sourceID int64,
	sideID int64,
	quantity string,
	price string,
	lockPx string,
	commissionAmount string,
	commissionCurrency string,
) (domain.Trade, error) {
	tradeXID, err := domain.ExternalIDFromBytes(tradeExtID)
	if err != nil {
		return domain.Trade{}, fmt.Errorf("store: decode trade external id: %w", err)
	}
	orderXID, err := domain.ExternalIDFromBytes(orderExtID)
	if err != nil {
		return domain.Trade{}, fmt.Errorf("store: decode trade order external id: %w", err)
	}
	parsedAt, err := time.Parse(time.RFC3339Nano, at)
	if err != nil {
		return domain.Trade{}, fmt.Errorf("store: parse trade at %q: %w", at, err)
	}
	source, err := dictionaries.code(sourceKindTable, "source", sourceID)
	if err != nil {
		return domain.Trade{}, err
	}
	side, err := dictionaries.code(orderSideTable, "order side", sideID)
	if err != nil {
		return domain.Trade{}, err
	}
	trade := domain.Trade{
		ExternalID: tradeXID,
		Order:      orderXID,
		Account:    domain.AccountID(account),
		BaseAsset:  baseAsset,
		QuoteAsset: quoteAsset,
		Principal:  principal.String,
		At:         parsedAt,
		Source:     domain.Source(source),
		Side:       domain.OrderSide(side),
		Quantity:   quantity,
		Price:      price,
		LockPrice:  lockPx,
	}
	if commissionAmount != "" || commissionCurrency != "" {
		trade.Commission = &domain.Commission{
			Amount:   commissionAmount,
			Currency: commissionCurrency,
		}
	}
	return trade, nil
}

func commissionAmount(c *domain.Commission) string {
	if c == nil {
		return ""
	}
	return c.Amount
}

func commissionCurrency(c *domain.Commission) string {
	if c == nil {
		return ""
	}
	return c.Currency
}

// validateCommission enforces the write-time Commission invariant shared by
// insertTrade and restoreTrade: a commission is either fully absent (both amount
// and currency empty) or fully present, and a present amount must be a valid
// decimal. A one-sided commission (exactly one of amount/currency set) would be
// silently dropped from the CommissionSubtotals rollup, understating the order
// commission, so it is rejected as invalid input rather than persisted.
func validateCommission(c *domain.Commission) error {
	amount := commissionAmount(c)
	currency := commissionCurrency(c)
	if (amount == "") != (currency == "") {
		return fmt.Errorf(
			"store: commission requires both amount and currency: %w",
			domain.ErrInvalid,
		)
	}
	if amount == "" {
		return nil
	}
	if _, err := decimal.NewFromString(amount); err != nil {
		return fmt.Errorf(
			"store: commission amount %q is not a valid decimal: %w",
			amount, domain.ErrInvalid,
		)
	}
	return nil
}

// commissionSubtotals rolls up the recorded commissions of the one order whose
// rows are already in memory. It folds them through the same commissionRollup
// the batched list read uses, so the detail and the list surface cannot report
// different totals for the same order.
func commissionSubtotals(
	order domain.ExternalID,
	trades []domain.Trade,
	events []domain.OrderEvent,
) ([]domain.Commission, error) {
	rollup := newCommissionRollup(1)
	for _, trade := range trades {
		if err := rollup.add(order, trade.Commission); err != nil {
			return nil, err
		}
	}
	for _, event := range events {
		if err := rollup.addEvent(order, event.Type, event.Payload); err != nil {
			return nil, err
		}
	}
	return rollup.subtotals(order), nil
}

// commissionRollup sums recorded order commissions per order and currency. It
// owns the rule that decides which commission counts, so the two order reads -
// the detail read folding in-memory rows and the batched list read folding SQL
// rows - share one implementation instead of two that must be kept in step.
// Currencies are grouped, never converted or collapsed, and amounts are summed
// as exact decimals.
type commissionRollup struct {
	byOrder map[domain.ExternalID]map[string]decimal.Decimal
}

func newCommissionRollup(orders int) *commissionRollup {
	return &commissionRollup{
		byOrder: make(map[domain.ExternalID]map[string]decimal.Decimal, orders),
	}
}

// add folds one recorded commission, the trade-row case. A commission missing
// either half is not a recorded commission and contributes nothing.
func (rollup *commissionRollup) add(
	order domain.ExternalID, commission *domain.Commission,
) error {
	if commission == nil || commission.Amount == "" || commission.Currency == "" {
		return nil
	}
	amount, err := decimal.NewFromString(commission.Amount)
	if err != nil {
		return fmt.Errorf(
			"store: parse commission amount %q: %w", commission.Amount, err)
	}
	amounts := rollup.byOrder[order]
	if amounts == nil {
		amounts = make(map[string]decimal.Decimal)
		rollup.byOrder[order] = amounts
	}
	amounts[commission.Currency] = amounts[commission.Currency].Add(amount)
	return nil
}

// addEvent folds one lifecycle event's commission, which counts only when no
// trade row already represents it.
func (rollup *commissionRollup) addEvent(
	order domain.ExternalID,
	eventType domain.OrderEventType,
	payload domain.OrderEventPayload,
) error {
	return rollup.add(
		order, feeOnlyExecutionReportCommission(eventType, payload))
}

// subtotals returns one order's per-currency subtotals; empty when the order
// has no recorded commission.
func (rollup *commissionRollup) subtotals(
	order domain.ExternalID,
) []domain.Commission {
	return commissionsFromAmountMap(rollup.byOrder[order])
}

// feeOnlyExecutionReportCommission returns the commission of an execution
// report that no trade row represents. A report without a fill writes no trade,
// so its lifecycle event is the only record of the fee and dropping it would
// lose the fee outright. Reports carrying a fill are accounted from their trade
// instead: the same report may persist both a fill event and a terminal-status
// event, so reading commission from those events would count it two or three
// times. Of the events one report writes, only its canonical status-change
// event contributes.
func feeOnlyExecutionReportCommission(
	eventType domain.OrderEventType,
	payload domain.OrderEventPayload,
) *domain.Commission {
	report := payload.ExecutionReport
	if report == nil || report.Commission == nil ||
		report.FillQuantity != "" || report.FillPrice != "" {
		return nil
	}
	canonicalEvent, ok := domain.ExecutionReportStatusChangeEvent(report.OrderStatus)
	if !ok || eventType != canonicalEvent {
		return nil
	}
	return report.Commission
}

// commissionSubtotalsByOrder rolls up recorded commissions for a list page. The
// order ids are chunked so the IN clauses stay inside the SQLite variable
// limit; every chunk feeds one rollup, which then answers per order.
func commissionSubtotalsByOrder(
	ctx context.Context,
	dictionaries *enumDictionaries,
	q sqlQueryer,
	orders []domain.ExternalID,
) (map[domain.ExternalID][]domain.Commission, error) {
	result := make(map[domain.ExternalID][]domain.Commission, len(orders))
	if len(orders) == 0 {
		return result, nil
	}

	rollup := newCommissionRollup(len(orders))
	for start := 0; start < len(orders); start += commissionSubtotalOrderBatchSize {
		end := start + commissionSubtotalOrderBatchSize
		if end > len(orders) {
			end = len(orders)
		}
		if err := accumulateCommissionSubtotalsByOrder(
			ctx, dictionaries, q, orders[start:end], rollup,
		); err != nil {
			return nil, err
		}
	}
	for _, order := range orders {
		result[order] = rollup.subtotals(order)
	}
	return result, nil
}

const commissionSubtotalOrderBatchSize = 500

func accumulateCommissionSubtotalsByOrder(
	ctx context.Context,
	dictionaries *enumDictionaries,
	q sqlQueryer,
	orders []domain.ExternalID,
	rollup *commissionRollup,
) error {
	placeholders := strings.TrimRight(strings.Repeat("?,", len(orders)), ",")
	args := make([]any, 0, len(orders))
	for _, order := range orders {
		args = append(args, order.Bytes())
	}
	rows, err := q.QueryContext(
		ctx,
		`SELECT o.external_id, t.commission_amount, t.commission_currency
FROM trade t
JOIN order_record o ON o.id = t.order_id
WHERE t.commission_amount <> ''
  AND t.commission_currency <> ''
  AND o.external_id IN (`+placeholders+`)`,
		args...,
	)
	if err != nil {
		return fmt.Errorf("store: list order commission subtotals: %w", err)
	}
	for rows.Next() {
		var orderBytes []byte
		var amountText, currency string
		if err := rows.Scan(&orderBytes, &amountText, &currency); err != nil {
			_ = rows.Close()
			return fmt.Errorf("store: scan order commission subtotal: %w", err)
		}
		order, err := domain.ExternalIDFromBytes(orderBytes)
		if err != nil {
			_ = rows.Close()
			return fmt.Errorf(
				"store: decode order commission external id: %w", err)
		}
		if err := rollup.add(
			order,
			&domain.Commission{Amount: amountText, Currency: currency},
		); err != nil {
			_ = rows.Close()
			return err
		}
	}
	if err := rows.Err(); err != nil {
		_ = rows.Close()
		return fmt.Errorf("store: iterate order commission subtotals: %w", err)
	}
	if err := rows.Close(); err != nil {
		return fmt.Errorf("store: close order commission subtotals: %w", err)
	}

	eventRows, err := q.QueryContext(
		ctx,
		`SELECT o.external_id, e.type_id, e.payload
FROM order_event e
JOIN order_record o ON o.id = e.order_id
WHERE o.external_id IN (`+placeholders+`)`,
		args...,
	)
	if err != nil {
		return fmt.Errorf("store: list order event commission subtotals: %w", err)
	}
	for eventRows.Next() {
		var orderBytes []byte
		var eventTypeID int64
		var payloadJSON string
		if err := eventRows.Scan(&orderBytes, &eventTypeID, &payloadJSON); err != nil {
			_ = eventRows.Close()
			return fmt.Errorf("store: scan order event commission subtotal: %w", err)
		}
		order, err := domain.ExternalIDFromBytes(orderBytes)
		if err != nil {
			_ = eventRows.Close()
			return fmt.Errorf(
				"store: decode order event commission external id: %w", err)
		}
		var payload domain.OrderEventPayload
		if err := json.Unmarshal([]byte(payloadJSON), &payload); err != nil {
			_ = eventRows.Close()
			return fmt.Errorf("store: decode order event commission payload: %w", err)
		}
		eventType, err := dictionaries.code(orderEventTypeTable, "order event type", eventTypeID)
		if err != nil {
			_ = eventRows.Close()
			return err
		}
		if err := rollup.addEvent(
			order,
			domain.OrderEventType(eventType),
			payload,
		); err != nil {
			_ = eventRows.Close()
			return err
		}
	}
	if err := eventRows.Err(); err != nil {
		_ = eventRows.Close()
		return fmt.Errorf("store: iterate order event commission subtotals: %w", err)
	}
	if err := eventRows.Close(); err != nil {
		return fmt.Errorf("store: close order event commission subtotals: %w", err)
	}
	return nil
}

func commissionsFromAmountMap(amounts map[string]decimal.Decimal) []domain.Commission {
	if len(amounts) == 0 {
		return []domain.Commission{}
	}
	currencies := make([]string, 0, len(amounts))
	for currency := range amounts {
		currencies = append(currencies, currency)
	}
	sort.Strings(currencies)
	out := make([]domain.Commission, 0, len(currencies))
	for _, currency := range currencies {
		out = append(out, domain.Commission{
			Amount:   amounts[currency].String(),
			Currency: currency,
		})
	}
	return out
}

// --- Settlement -------------------------------------------------------------

// RecordOrderSettlement persists one fill/settlement atomically in a single
// transaction: the optional execution-report identity and all of its event
// links, per-asset engine balance snapshots, the engine-applied account blocks,
// the optional trade, the fill event(s),
// the optional lock rewrite and the order status advance commit or roll back
// together. When AllowedFrom is non-empty the status UPDATE is guarded and a
// disallowed current status yields domain.ErrConflict with nothing written;
// otherwise a missing order yields domain.ErrNotFound. The block-audit row is
// NOT part of this tx; callers write it separately after a successful commit.
func (r *realmStore) RecordOrderSettlement(
	ctx context.Context, st domain.OrderSettlement,
) (domain.ExternalID, error) {
	return r.recordOrderSettlement(ctx, st, nil)
}

func (r *realmStore) RecordOrderSettlementWithAttestation(
	ctx context.Context, st domain.OrderSettlement, attest fwstore.EventAttestor,
) (domain.ExternalID, error) {
	return r.recordOrderSettlement(ctx, st, attest)
}

func (r *realmStore) recordOrderSettlement(
	ctx context.Context, st domain.OrderSettlement, attest fwstore.EventAttestor,
) (domain.ExternalID, error) {
	db, err := r.db()
	if err != nil {
		return "", err
	}
	dictionaries, err := r.dictionaries()
	if err != nil {
		return "", err
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return "", fmt.Errorf("store: begin record_order_settlement: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	reportID, err := r.recordOrderSettlementTx(ctx, dictionaries, tx, st, attest)
	if err != nil {
		return "", err
	}
	if err := tx.Commit(); err != nil {
		return "", fmt.Errorf("store: commit record_order_settlement: %w", err)
	}
	if st.ReportID != nil {
		*st.ReportID = reportID
	}
	return reportID, nil
}

func (r *realmStore) recordOrderSettlementTx(
	ctx context.Context,
	dictionaries *enumDictionaries,
	tx *sql.Tx,
	st domain.OrderSettlement,
	attest fwstore.EventAttestor,
) (domain.ExternalID, error) {
	if st.Order.IsZero() {
		return "", fmt.Errorf("store: settlement order is required: %w", domain.ErrInvalid)
	}
	// Resolve the settling account once; balance and blocks reuse it. The
	// account is the fill's account, always present on a settlement.
	accountID, err := resolveAccountID(ctx, tx, st.Account)
	if err != nil {
		return "", err
	}
	// Resolve the order surrogate id before any writes. Events, the optional
	// report, lock rewrite and status advance all reuse it.
	orderID, err := lookupOrderID(ctx, tx, st.Order)
	if err != nil {
		return "", err
	}
	if attest != nil && len(st.Events) == 0 {
		return "", fmt.Errorf(
			"store: settlement has no event to attest: %w", domain.ErrInvalid,
		)
	}
	if st.ReportID != nil && len(st.Events) == 0 {
		return "", fmt.Errorf(
			"store: execution report has no events: %w", domain.ErrInvalid,
		)
	}
	if st.AccountPnl != "" {
		if _, err := domain.AddDecimals("", st.AccountPnl); err != nil {
			return "", fmt.Errorf("store: settlement account pnl %q: %w", st.Account, err)
		}
	}
	reportID, reportRowID, err := insertExecutionReportTx(
		ctx, tx, orderID, st.ReportID,
	)
	if err != nil {
		return "", err
	}

	// The engine reports the P&L value and its halt as one fact, so both columns
	// move together. NULL is the absence of a value, which a halt always is; a
	// settlement reporting neither leaves the stored pair untouched.
	if st.AccountPnlHaltReason != "" || st.AccountPnl != "" {
		var storedPnl any
		if st.AccountPnl != "" && st.AccountPnlHaltReason == "" {
			storedPnl = st.AccountPnl
		}
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE account SET pnl = ?, pnl_halt_reason = ? WHERE id = ?`,
			storedPnl,
			st.AccountPnlHaltReason,
			accountID,
		); err != nil {
			return "", fmt.Errorf("store: settlement account pnl %q: %w", st.Account, err)
		}
	}

	// Per-asset balance snapshots are merged inside this transaction; fields the
	// engine omitted preserve their prior values.
	for _, bal := range st.Balances {
		if err := settleBalanceTx(ctx, tx, accountID, bal); err != nil {
			return "", err
		}
	}

	// Mirror engine-applied account blocks (the block UPDATE only; the audit row
	// stays a post-commit write owned by the caller). A block names its own
	// account, which may differ from the fill account in principle, so resolve it.
	for _, blk := range st.Blocks {
		blkAccountID, err := resolveAccountID(ctx, tx, blk.Account)
		if err != nil {
			return "", err
		}
		// The reason is engine-composed, never operator input: refusing it would
		// drop a real kill-switch record, so it is normalized to the rule the
		// restore path validates rather than rejected.
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE account SET blocked = ?, block_reason = ? WHERE id = ?`,
			true, domain.NormalizeReason(blk.Reason), blkAccountID,
		); err != nil {
			return "", fmt.Errorf("store: settlement mirror block %q: %w", blk.Account, err)
		}
	}

	// Trade row.
	if st.Trade != nil {
		if _, _, err := r.insertTrade(ctx, tx, *st.Trade); err != nil {
			return "", err
		}
	}

	// Fill event(s).
	for _, ev := range st.Events {
		if !reportID.IsZero() && ev.Payload.ExecutionReport != nil {
			request := *ev.Payload.ExecutionReport
			request.ExternalID = reportID
			ev.Payload.ExecutionReport = &request
		}
		recorded, eventRowID, err := appendOrderEventReturningTx(
			ctx, dictionaries, tx, orderID, ev,
		)
		if err != nil {
			return "", err
		}
		if reportRowID != 0 {
			if _, err := tx.ExecContext(
				ctx,
				`INSERT INTO execution_report_event (report_id, event_id) VALUES (?, ?)`,
				reportRowID,
				eventRowID,
			); err != nil {
				return "", fmt.Errorf("store: link execution report event: %w", err)
			}
		}
		if err := attestOrderEventTx(ctx, dictionaries, tx, recorded, attest); err != nil {
			return "", err
		}
	}

	// Lock rewrite: only when explicitly requested (nil-vs-empty matters: an
	// empty non-nil slice clears the column, nil leaves it).
	if st.SetLock {
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE order_record SET lock = ? WHERE id = ?`,
			nullableBlob(st.Lock), orderID,
		); err != nil {
			return "", fmt.Errorf("store: settlement lock: %w", err)
		}
	}

	// Remaining open quantity: the caller carries the report's LeavesQty; an
	// empty value leaves the column untouched.
	if st.Leaves != "" {
		if _, err := tx.ExecContext(
			ctx,
			`UPDATE order_record SET leaves_quantity = ? WHERE id = ?`,
			st.Leaves, orderID,
		); err != nil {
			return "", fmt.Errorf("store: settlement leaves: %w", err)
		}
	}

	// Status advance last; guarded only when AllowedFrom is set.
	if err := guardedOrderStatus(
		ctx, dictionaries, tx, orderID, st.Order, st.OrderStatus, st.AllowedFrom,
	); err != nil {
		return "", err
	}

	return reportID, nil
}

func insertExecutionReportTx(
	ctx context.Context,
	tx *sql.Tx,
	orderID int64,
	reportID *domain.ExternalID,
) (domain.ExternalID, int64, error) {
	if reportID == nil {
		return "", 0, nil
	}
	xid, err := externalIDForInsert(*reportID)
	if err != nil {
		return "", 0, err
	}
	result, err := tx.ExecContext(
		ctx,
		`INSERT INTO execution_report (external_id, order_id, at) VALUES (?, ?, ?)`,
		xid.Bytes(),
		orderID,
		nowStr(),
	)
	if err != nil {
		if isSQLiteUnique(err) {
			return "", 0, fmt.Errorf(
				"execution report %q: %w", xid.String(), domain.ErrAlreadyExists,
			)
		}
		return "", 0, fmt.Errorf("store: insert execution report: %w", err)
	}
	reportRowID, err := result.LastInsertId()
	if err != nil {
		return "", 0, fmt.Errorf("store: execution report row id: %w", err)
	}
	return xid, reportRowID, nil
}

// guardedOrderStatus advances an order's status inside tx, addressing it by its
// already-resolved surrogate id. When allowedFrom is non-empty the UPDATE only
// matches rows already in one of those statuses; a 0-rows result then means
// either the order is missing (domain.ErrNotFound) or its current status is
// disallowed (domain.ErrConflict), distinguished by a follow-up SELECT in the
// same tx. When allowedFrom is empty the UPDATE is unguarded and 0 rows means a
// missing order. The order external id is carried for error messages only.
func guardedOrderStatus(
	ctx context.Context,
	dictionaries *enumDictionaries,
	tx *sql.Tx,
	orderID int64,
	order domain.ExternalID,
	status domain.OrderStatus,
	allowedFrom []domain.OrderStatus,
) error {
	statusID, err := dictionaries.id(orderStatusTable, "order status", string(status))
	if err != nil {
		return err
	}
	args := []any{statusID, orderID}
	q := `UPDATE order_record SET status_id = ? WHERE id = ?`
	if len(allowedFrom) > 0 {
		placeholders := strings.TrimSuffix(strings.Repeat("?,", len(allowedFrom)), ",")
		q += fmt.Sprintf(` AND status_id IN (%s)`, placeholders)
		for _, s := range allowedFrom {
			id, err := dictionaries.id(orderStatusTable, "order status", string(s))
			if err != nil {
				return err
			}
			args = append(args, id)
		}
	}
	res, err := tx.ExecContext(ctx, q, args...)
	if err != nil {
		return fmt.Errorf("store: resolve order %q status: %w", order.String(), err)
	}
	n, err := res.RowsAffected()
	if err != nil {
		return fmt.Errorf("store: resolve order %q status rows: %w", order.String(), err)
	}
	if n > 0 {
		return nil
	}
	// No row advanced: distinguish a missing order from a disallowed status.
	var curID int64
	err = tx.QueryRowContext(
		ctx, `SELECT status_id FROM order_record WHERE id = ?`, orderID,
	).Scan(&curID)
	if errors.Is(err, sql.ErrNoRows) {
		return fmt.Errorf("order %q: %w", order.String(), domain.ErrNotFound)
	}
	if err != nil {
		return fmt.Errorf("store: resolve order %q status probe: %w", order.String(), err)
	}
	cur, err := dictionaries.code(orderStatusTable, "order status", curID)
	if err != nil {
		return err
	}
	return fmt.Errorf(
		"store: resolve order %q: status %q: %w", order.String(), cur, domain.ErrConflict,
	)
}

func appendOrderEventReturningTx(
	ctx context.Context,
	dictionaries *enumDictionaries,
	tx *sql.Tx,
	orderID int64,
	ev domain.OrderEvent,
) (domain.OrderEvent, int64, error) {
	ev.Source = storedSource(ev.Source)
	principalID, err := resolveOptionalPrincipalID(ctx, tx, ev.Principal)
	if err != nil {
		return domain.OrderEvent{}, 0, err
	}
	typeID, err := dictionaries.id(orderEventTypeTable, "order event type", string(ev.Type))
	if err != nil {
		return domain.OrderEvent{}, 0, err
	}
	sourceID, err := dictionaries.id(sourceKindTable, "source", string(ev.Source))
	if err != nil {
		return domain.OrderEvent{}, 0, err
	}
	xid, err := newExternalID()
	if err != nil {
		return domain.OrderEvent{}, 0, err
	}
	at := nowStr()
	payloadJSON, err := json.Marshal(ev.Payload)
	if err != nil {
		return domain.OrderEvent{}, 0, fmt.Errorf("store: marshal event payload: %w", err)
	}
	result, err := tx.ExecContext(
		ctx,
		`INSERT INTO order_event
		 (external_id, order_id, principal_id, at, type_id, source_id, payload)
		 VALUES (?, ?, ?, ?, ?, ?, ?)`,
		xid.Bytes(), orderID, principalID, at,
		typeID, sourceID, string(payloadJSON),
	)
	if err != nil {
		return domain.OrderEvent{}, 0, fmt.Errorf("store: append order event: %w", err)
	}
	eventRowID, err := result.LastInsertId()
	if err != nil {
		return domain.OrderEvent{}, 0, fmt.Errorf("store: order event row id: %w", err)
	}
	ev.ExternalID = xid
	ev.At = mustParseTime(at)
	return ev, eventRowID, nil
}

func attestOrderEventTx(
	ctx context.Context,
	dictionaries *enumDictionaries,
	tx *sql.Tx,
	event domain.OrderEvent,
	attest fwstore.EventAttestor,
) error {
	if attest == nil {
		return nil
	}
	att, ok, err := attest(ctx, event)
	if err != nil {
		return err
	}
	if !ok {
		return fmt.Errorf(
			"store: event %s has no attestation payload: %w",
			event.Type, domain.ErrInvalid,
		)
	}
	return putEventAttestationTx(ctx, dictionaries, tx, event.ExternalID, att)
}

// settleBalanceTx applies one per-asset fill outcome inside tx. Available,
// held, incoming, realized PnL, and average entry price are independent
// engine-returned absolutes; an absent result preserves the prior value. The
// balance table is owned by another store group; this method
// touches it with direct SQL (never the public balance methods) to keep the
// whole settlement atomic.
func settleBalanceTx(
	ctx context.Context,
	tx *sql.Tx,
	accountID int64,
	bal domain.BalanceSettlement,
) error {
	assetID, err := resolveAssetID(ctx, tx, bal.Asset)
	if err != nil {
		return err
	}
	var prevAvail, prevHeld, prevIncoming, prevPnlHaltReason, prevAvgPx string
	var prevRealized sql.NullString
	err = tx.QueryRowContext(
		ctx,
		`SELECT available, held, incoming, realized_pnl, realized_pnl_halt_reason, average_entry_price
		 FROM balance WHERE account_id = ? AND asset_id = ?`,
		accountID, assetID,
	).Scan(&prevAvail, &prevHeld, &prevIncoming, &prevRealized, &prevPnlHaltReason, &prevAvgPx)
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return fmt.Errorf("store: settle balance %q read: %w", bal.Asset, err)
	}

	available := settleOrZero(settlementResultOrPrevious(bal.Outcome.BalanceResult, prevAvail))
	held := settleOrZero(settlementResultOrPrevious(bal.Outcome.HeldResult, prevHeld))
	incoming := settleOrZero(settlementResultOrPrevious(bal.Outcome.IncomingResult, prevIncoming))
	realized := settlementResultOrPrevious(
		bal.Outcome.RealizedPnlResult, prevRealized.String)
	pnlHaltReason := settlementPnlHaltReason(
		bal.Outcome.RealizedPnlHaltReason,
		prevPnlHaltReason,
		bal.Outcome.RealizedPnlResult != "",
	)
	if pnlHaltReason != "" {
		realized = ""
	}
	averageEntryPrice := settlementResultOrPrevious(
		bal.Outcome.AverageEntryPrice, prevAvgPx)
	if decimalZeroOrEmpty(available) &&
		decimalZeroOrEmpty(held) &&
		decimalZeroOrEmpty(incoming) {
		// A closed position has no cost basis; realised PnL remains independent.
		averageEntryPrice = ""
	}
	if _, err := tx.ExecContext(
		ctx,
		`INSERT OR REPLACE INTO balance
		 (account_id, asset_id, available, held,
		  incoming, realized_pnl, realized_pnl_halt_reason, average_entry_price, updated_at)
		 VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)`,
		accountID, assetID,
		available, held, incoming,
		nullablePnl(realized, domain.PnlHaltReason(pnlHaltReason)),
		pnlHaltReason, averageEntryPrice,
		nowStr(),
	); err != nil {
		return fmt.Errorf("store: settle balance %q write: %w", bal.Asset, err)
	}
	if err := pruneEmptySettlementBalanceTx(
		ctx, tx, accountID, assetID, bal.Asset,
		available, held, incoming, realized, pnlHaltReason, averageEntryPrice,
	); err != nil {
		return err
	}
	return nil
}

func pruneEmptySettlementBalanceTx(
	ctx context.Context,
	tx *sql.Tx,
	accountID int64,
	assetID int64,
	asset string,
	available string,
	held string,
	incoming string,
	realized string,
	pnlHaltReason string,
	averageEntryPrice string,
) error {
	if !balanceAmountsEmpty(available, held, incoming, realized, pnlHaltReason, averageEntryPrice) {
		return nil
	}
	if _, err := tx.ExecContext(
		ctx,
		`DELETE FROM balance WHERE account_id = ? AND asset_id = ?`,
		accountID, assetID,
	); err != nil {
		return fmt.Errorf("store: prune empty settlement balance %q: %w", asset, err)
	}
	return nil
}

func balanceAmountsEmpty(
	available string, held string, incoming string, realized string, pnlHaltReason string, averageEntryPrice string,
) bool {
	return decimalZeroOrEmpty(available) &&
		decimalZeroOrEmpty(held) &&
		decimalZeroOrEmpty(incoming) &&
		decimalZeroOrEmpty(realized) &&
		pnlHaltReason == "" &&
		decimalZeroOrEmpty(averageEntryPrice)
}

func settlementPnlHaltReason(next domain.PnlHaltReason, prev string, successfulPnlResult bool) string {
	if next != "" {
		return string(next)
	}
	if successfulPnlResult {
		return ""
	}
	return prev
}

func decimalZeroOrEmpty(value string) bool {
	if value == "" {
		return true
	}
	parsed, err := decimal.NewFromString(value)
	return err == nil && parsed.IsZero()
}

// --- Orders-group small helpers ---------------------------------------------

// lookupOrderID resolves an order's external id to its surrogate id, mapping a
// missing order onto domain.ErrNotFound. It is the orders-group analogue of the
// dictionary resolvers in store.go; it joins the order's children and the
// settlement writes to the order without exposing the surrogate id.
func lookupOrderID(
	ctx context.Context, q sqlQueryer, id domain.ExternalID,
) (int64, error) {
	var orderID int64
	err := q.QueryRowContext(
		ctx, `SELECT id FROM order_record WHERE external_id = ?`, id.Bytes(),
	).Scan(&orderID)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, fmt.Errorf("order %q: %w", id.String(), domain.ErrNotFound)
	}
	if err != nil {
		return 0, fmt.Errorf("store: resolve order %q: %w", id.String(), err)
	}
	return orderID, nil
}

// lookupOrderEventID resolves an event's external id to its surrogate id,
// mapping a missing event onto domain.ErrNotFound. It is the analogue of
// lookupOrderID for the event stream; it keys the 1:1 attestation onto the event
// without exposing the surrogate id.
func lookupOrderEventID(
	ctx context.Context, q sqlQueryer, id domain.ExternalID,
) (int64, error) {
	var eventID int64
	err := q.QueryRowContext(
		ctx, `SELECT id FROM order_event WHERE external_id = ?`, id.Bytes(),
	).Scan(&eventID)
	if errors.Is(err, sql.ErrNoRows) {
		return 0, fmt.Errorf("order event %q: %w", id.String(), domain.ErrNotFound)
	}
	if err != nil {
		return 0, fmt.Errorf("store: resolve order event %q: %w", id.String(), err)
	}
	return eventID, nil
}

// nullableBlob maps a nil byte slice to a NULL column value and a non-nil slice
// (including an empty one) to itself, so the lock column distinguishes "no lock"
// (NULL) from a present-but-empty serialized lock.
func nullableBlob(b []byte) any {
	if b == nil {
		return nil
	}
	return b
}

// mustParseTime parses an RFC3339Nano string the store itself just formatted via
// nowStr; the format is guaranteed, so a parse error is impossible and the zero
// time is returned defensively rather than panicking on the write path.
func mustParseTime(s string) time.Time {
	t, _ := time.Parse(time.RFC3339Nano, s)
	return t
}

// settleOrZero maps an empty amount string to "0" so a balance column is never
// written empty.
func settleOrZero(s string) string {
	if s == "" {
		return "0"
	}
	return s
}

// nullablePnl stores an engine-reported P&L value only while it is
// authoritative. Empty and halted states are represented as SQL NULL, never as
// a zero Officer invented.
func nullablePnl(pnl string, haltReason domain.PnlHaltReason) any {
	if pnl == "" || haltReason != "" {
		return nil
	}
	return pnl
}

func settlementResultOrPrevious(next, prev string) string {
	if next != "" {
		return next
	}
	return prev
}
