func (r *realmStore) RecordOrderSubmissionWithAttestation(
	ctx context.Context,
	o domain.Order,
	submitted domain.OrderEvent,
	apply func(domain.Order) (domain.OrderSettlement, error),
	attest fwstore.EventAttestor,
) (domain.Order, error) {
	return r.recordOrderSubmission(ctx, o, submitted, apply, attest)
}

func (r *realmStore) recordOrderSubmission(
	ctx context.Context,
	o domain.Order,
	submitted domain.OrderEvent,
	apply func(domain.Order) (domain.OrderSettlement, error),
	attest fwstore.EventAttestor,
) (domain.Order, error) {
	db, err := r.db()
	if err != nil {
		return domain.Order{}, err
	}
	dictionaries, err := r.dictionaries()
	if err != nil {
		return domain.Order{}, err
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return domain.Order{}, fmt.Errorf("store: begin order submission: %w", err)
	}
	defer func() { _ = tx.Rollback() }()

	order, err := createOrderTx(ctx, dictionaries, tx, o)
	if err != nil {
		return domain.Order{}, err
	}
	orderID, err := lookupOrderID(ctx, tx, order.ExternalID)
	if err != nil {
		return domain.Order{}, err
	}
	if submitted.Order.IsZero() {
		submitted.Order = order.ExternalID
	}
	recordedSubmitted, _, err := appendOrderEventReturningTx(
		ctx, dictionaries, tx, orderID, submitted,
	)
	if err != nil {
		return domain.Order{}, err
	}

	settlement, err := apply(order)
	if err != nil {
		return domain.Order{}, err
	}
	if err := attestOrderEventTx(ctx, dictionaries, tx, recordedSubmitted, attest); err != nil {
		return domain.Order{}, err
	}
	if settlement.Order.IsZero() {
		settlement.Order = order.ExternalID
	}
	if settlement.Account == "" {
		settlement.Account = order.Account
	}
	if _, err := r.recordOrderSettlementTx(ctx, dictionaries, tx, settlement, attest); err != nil {
		return domain.Order{}, err
	}
	if err := tx.Commit(); err != nil {
		return domain.Order{}, fmt.Errorf("store: commit order submission: %w", err)
	}

	order.Status = settlement.OrderStatus
	order.Lock = settlement.Lock
	if settlement.Leaves != "" {
		order.Leaves = settlement.Leaves
	}
	return order, nil
}

