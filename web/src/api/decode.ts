/** Whether `value` is a plain object: not null and not an array. */
export function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/**
 * The error a strict decoder throws for a response field that breaks the
 * contract, such as `account mode response: mode must be a string`.
 */
export function invalid(
  response: string,
  field: string,
  requirement: string,
): Error {
  return new Error(`${response} response: ${field} ${requirement}`);
}
